#!/usr/bin/env python3
"""Rebuild the notes index: data/notes.json, feed.xml and the home page list.

Lists the owner's PUBLIC repositories tagged with the `research-note` topic
via the GitHub API and writes three things the site serves:

  * `data/notes.json`: the generated notes list. Each entry uses the repo's
    description as its title and the repo's homepage (the note's GitHub Pages
    URL) as its link, falling back to the conventional Pages URL.
  * `feed.xml`: the Atom feed, one entry per note.
  * `index.html`: the note cards between the `notes:start` / `notes:end`
    markers, so the home page lists every note without any JavaScript.

`data/notes-meta.json` is the hand-written half: a one-line finding, a kind
and a status per note, keyed by the note's code URL. The generator only reads
it, so hand edits there are never overwritten.

Usage:
    python3 bin/build_index.py            # fetch from GitHub, rebuild all three
    python3 bin/build_index.py --offline  # re-render index.html from the
                                          # existing notes.json (no network)

Pure stdlib. `GITHUB_TOKEN` is used when present; anonymous requests work
within the unauthenticated rate limit. Prints "unchanged" when every output is
already current.

Titles are HTML-escaped on use: the list renders on the public site, and even
self-authored metadata should not be able to inject markup. Link DESTINATIONS
are validated (not escaped): a crafted homepage on any repo tagged
research-note would otherwise land verbatim in the published list.
"""

from __future__ import annotations

import html
import json
import os
import sys
import urllib.request
from pathlib import Path

OWNER = "KiwiMaddog2020"
TOPIC = "research-note"
ROOT = Path(__file__).resolve().parent.parent
NOTES = ROOT / "data" / "notes.json"
META = ROOT / "data" / "notes-meta.json"
HOME = ROOT / "index.html"
HOME_START = "<!-- notes:start (generated by bin/build_index.py, do not edit by hand) -->"
HOME_END = "<!-- notes:end -->"
STATUSES = {"holds", "revised", "superseded", "untested"}
FEED = ROOT / "feed.xml"
SITE_URL = f"https://{OWNER.lower()}.github.io/"
SITE_TITLE = "Arbiter Machinae · Research notes"


def _api(path: str):
    req = urllib.request.Request(
        f"https://api.github.com{path}",
        headers={
            "Accept": "application/vnd.github+json",
            "User-Agent": f"{OWNER}-research-index",
            **(
                {"Authorization": f"Bearer {os.environ['GITHUB_TOKEN']}"}
                if os.environ.get("GITHUB_TOKEN")
                else {}
            ),
        },
    )
    with urllib.request.urlopen(req, timeout=30) as resp:
        return json.load(resp)


def _esc(text: str) -> str:
    """HTML/XML-escape untrusted text for element or attribute context."""
    return html.escape(text, quote=True)


def _safe_page_url(homepage: str, name: str) -> str:
    """Validate a link DESTINATION; fall back to the conventional Pages URL.

    A crafted homepage on any repo tagged research-note (javascript: scheme, a
    quote breakout into attribute context, or control characters) would
    otherwise land verbatim in the public list.
    """
    from urllib.parse import urlsplit

    fallback = f"{SITE_URL}{name}/"
    candidate = (homepage or "").strip()
    if not candidate:
        return fallback
    try:
        parts = urlsplit(candidate)
    except ValueError:
        return fallback
    if parts.scheme not in ("http", "https") or not parts.netloc:
        return fallback
    if any(ch in candidate for ch in "()<>'\"\\ "):
        return fallback
    # Reject ASCII control chars and DEL (tab/newline survive urlsplit and
    # would land raw in the published attribute).
    if any(ord(ch) < 0x21 or ord(ch) == 0x7F for ch in candidate):
        return fallback
    return candidate


# Hard stop for pagination: 20 pages is 2,000 repositories, far beyond this account.
MAX_PAGES = 20


def note_repos() -> list[dict]:
    repos = []
    page = 1
    while page <= MAX_PAGES:
        batch = _api(f"/users/{OWNER}/repos?per_page=100&page={page}&sort=created&direction=desc")
        if not batch:
            break
        repos.extend(batch)
        if len(batch) < 100:
            break
        page += 1
    return [
        r
        for r in repos
        if not r.get("private")
        and not r.get("fork")
        and TOPIC in (r.get("topics") or [])
        and r.get("name") != f"{OWNER.lower()}.github.io"
    ]


def render_notes_json(repos: list[dict]) -> str:
    """The generated notes list.

    Titles are stored raw (escaped when rendered); destinations are validated
    here so a bad homepage cannot reach the page.
    """
    notes = []
    for r in repos:
        notes.append(
            {
                "title": (r.get("description") or r["name"]).strip(),
                "url": _safe_page_url(r.get("homepage") or "", r["name"]),
                "code": r["html_url"],
                "date": (r.get("created_at") or "")[:10],
            }
        )
    return json.dumps(notes, indent=2) + "\n"


def render_feed(repos: list[dict]) -> str:
    """Atom feed, one entry per note.

    Entry timestamps use the repo's created_at: it is stable (pushed_at
    churns on every code commit, which would re-mark entries unread for
    subscribers), and a note is "published" when its repo is.
    """
    entries = []
    newest = ""
    for r in repos:
        title = _esc((r.get("description") or r["name"]).strip())
        page = _safe_page_url(r.get("homepage") or "", r["name"])
        stamp = r.get("created_at") or "1970-01-01T00:00:00Z"
        newest = max(newest, stamp)
        entries.append(
            "  <entry>\n"
            f"    <title>{title}</title>\n"
            f'    <link href="{_esc(page)}"/>\n'
            f"    <id>{_esc(page)}</id>\n"
            f"    <updated>{_esc(stamp)}</updated>\n"
            f"    <summary>{title}</summary>\n"
            "  </entry>"
        )
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<?xml-stylesheet type="text/xsl" href="/feed.xsl"?>\n'
        '<feed xmlns="http://www.w3.org/2005/Atom">\n'
        f"  <title>{_esc(SITE_TITLE)}</title>\n"
        f'  <link href="{SITE_URL}feed.xml" rel="self"/>\n'
        f'  <link href="{SITE_URL}"/>\n'
        f"  <id>{SITE_URL}</id>\n"
        f"  <updated>{_esc(newest)}</updated>\n"
        "  <author><name>Kevin Madson</name></author>\n"
        + "\n".join(entries)
        + "\n</feed>\n"
    )


def load_meta() -> dict:
    """Hand-written per-note details, keyed by code URL. Missing file means none."""
    if not META.exists():
        return {}
    return json.loads(META.read_text(encoding="utf-8"))


def _safe_code_url(url: str) -> str:
    """Only GitHub repo links for this owner are allowed in the code slot."""
    prefix = f"https://github.com/{OWNER}/"
    return url if isinstance(url, str) and url.startswith(prefix) else f"https://github.com/{OWNER}"


def _safe_note_url(url: str) -> str:
    """Re-check a stored note link: notes.json could have been edited by hand."""
    return url if isinstance(url, str) and url.startswith(SITE_URL) else SITE_URL


def render_home_cards(notes: list[dict], meta: dict) -> str:
    """The note cards for index.html. Everything from data files is escaped."""
    cards = []
    for n in notes:
        m = meta.get(n.get("code", ""), {})
        status = m.get("status", "untested")
        if status not in STATUSES:
            status = "untested"
        label = _esc(m.get("label") or m.get("kind") or "note")
        find = m.get("finding", "")
        cards.append(
            '        <li class="nb-card" data-nb-tilt>\n'
            f'          <span class="nb-status" data-status="{status}">{label}</span>\n'
            f'          <a class="nb-card-link" data-nb-note href="{_esc(_safe_note_url(n.get("url", "")))}">'
            f'<span class="nb-card-title" data-nb-note-title>{_esc(n.get("title", ""))}</span></a>\n'
            + (f'          <p class="nb-card-find">{_esc(find)}</p>\n' if find else "")
            + f'          <a class="nb-card-code" href="{_esc(_safe_code_url(n.get("code", "")))}">code</a>\n'
            "        </li>"
        )
    return "\n".join(cards)


def stamp_home(page: str, cards: str) -> str:
    """Replace whatever sits between the two markers. Raises if they are missing."""
    start = page.find(HOME_START)
    end = page.find(HOME_END)
    if start == -1 or end == -1 or end < start:
        raise ValueError("index.html is missing the notes:start / notes:end markers")
    return page[: start + len(HOME_START)] + "\n" + cards + "\n        " + page[end:]


def rebuild_home(notes: list[dict]) -> bool:
    """Re-render the home page list. Returns True when the file changed."""
    page = HOME.read_text(encoding="utf-8")
    stamped = stamp_home(page, render_home_cards(notes, load_meta()))
    if stamped == page:
        return False
    HOME.write_text(stamped, encoding="utf-8")
    return True


def main(argv: list[str] | None = None) -> int:
    argv = sys.argv[1:] if argv is None else argv
    if "--offline" in argv:
        notes_now = json.loads(NOTES.read_text(encoding="utf-8"))
        print("rebuilt: index.html" if rebuild_home(notes_now) else "unchanged")
        return 0
    repos = note_repos()
    if not repos:
        # FAIL SAFE: an empty result is more likely a visibility or API
        # hiccup than a real "no notes exist" state, and a hand-seeded entry
        # must survive a rebuild that runs before a repo flips public.
        # (A nonempty-but-smaller list DOES overwrite: removing the topic
        # from a repo is the intended de-listing mechanism.)
        print("no public research-note repos found; leaving notes unchanged")
        return 0
    changed = []
    notes = render_notes_json(repos)
    feed = render_feed(repos)
    # Render the home page before writing anything, so a broken page (lost
    # markers, bad meta file) stops the run with all three outputs untouched.
    page = HOME.read_text(encoding="utf-8")
    stamped = stamp_home(page, render_home_cards(json.loads(notes), load_meta()))
    NOTES.parent.mkdir(parents=True, exist_ok=True)
    if not NOTES.exists() or NOTES.read_text(encoding="utf-8") != notes:
        NOTES.write_text(notes, encoding="utf-8")
        changed.append("data/notes.json")
    if not FEED.exists() or FEED.read_text(encoding="utf-8") != feed:
        FEED.write_text(feed, encoding="utf-8")
        changed.append("feed.xml")
    if stamped != page:
        HOME.write_text(stamped, encoding="utf-8")
        changed.append("index.html")
    print("rebuilt: " + ", ".join(changed) if changed else "unchanged")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
